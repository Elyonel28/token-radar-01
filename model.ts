// Token radar, model "radar-2": a comps-calibrated implied value.
//
// A protocol that records no token is priced the way the market prices the
// tokens that already trade. For every live-token protocol the snapshot
// carries, its FDV/TVL multiple (market cap over TVL) is a comparable. A
// pre-token protocol's implied value is its own TVL times the multiple the
// market pays for its category, dampened for growth and for age:
//
//   multiple   = median FDV/TVL of the live protocols in this category
//                (at least 3 comparables, else the global median), capped
//   base       = tvl_usd x multiple
//   growth     = clamp(change_7d, -50, 100) per cent
//   growthMult = 1 + (growth / 100) x 0.35          (dampened: a hot week
//                                                     lifts value, it does
//                                                     not double it)
//   maturity   = 0.70 + 0.30 x ln(1 + age) / ln(1 + 1095)
//                                                     (log age: an old
//                                                     protocol is worth more
//                                                     than a new one, with
//                                                     diminishing returns)
//   implied    = max(1, round(base x growthMult x maturity))
//
// No protocol name is ever special-cased: the same function scores every
// row, and every number it uses comes from the snapshot itself (the live
// protocols' market caps and TVLs, each row's own TVL, growth and age).
// The board ranks every pre-token protocol the snapshot can rank (the 40
// watchlist slugs plus every rankable protocol below the floor), and the
// live-token protocols are kept apart as the market's own values, never
// mixed into the ranked board. Rankable means the protocol meets the
// house's own definition of still waiting on a launch: it records no
// token, and it is not a wrapped, staked or bridged product of a token
// that already trades (WBTC, Binance staked ETH and USDT0 are the
// rule's own examples), not an exchange, and not a versioned pool.

